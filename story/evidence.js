function renderEvidence(sceneId) {
  const ids = evidenceScenes[sceneId];
  if (!ids) { evidenceOpen.hidden = true; return; }
  evidenceOpen.hidden = false;
  const lang = evidenceLanguage();
  const t = evidenceUI[lang];
  const index = lang === 'en' ? 0 : lang === 'tw' ? 1 : 2;
  const photo = evidencePhotos[ids[0]];
  const scene = document.getElementById(sceneId);
  const heading = scene?.querySelector('h2');
  const title = heading ? [...heading.childNodes].map(node => node.nodeName === 'BR' ? ' ' : node.textContent).join('').replace(/\s+/g, ' ').trim() : scene?.getAttribute('aria-label') || sceneId;
  document.getElementById('evidence-thumb').src = photo.src;
  document.getElementById('evidence-float-label').textContent = t[0];
  document.getElementById('evidence-float-count').textContent = `${String(ids.length).padStart(2, '0')} / ${t[1]}`;
  document.getElementById('evidence-title').textContent = title;
  document.getElementById('evidence-kicker').textContent = `${t[0]} / ${String([...document.querySelectorAll('[data-scene]')].findIndex(item => item.id === sceneId) + 1).padStart(2, '0')}`;
  document.getElementById('evidence-intro').textContent = t[3];
  document.getElementById('evidence-main-link').textContent = t[4];
  evidenceClose.setAttribute('aria-label', t[7]);
  evidenceOpen.setAttribute('aria-label', t[8]);
  evidenceCards.replaceChildren();
  ids.forEach((id, i) => {
    const item = evidencePhotos[id];
    const figure = document.createElement('figure');
    const anchor = document.createElement('a');
    anchor.href = item.url;
    anchor.target = '_blank';
    anchor.rel = 'noopener noreferrer';
    anchor.setAttribute('aria-label', `${t[5]}: ${item.caption[index]}`);
    const img = document.createElement('img');
    img.src = item.src;
    img.alt = item.caption[index];
    img.loading = 'lazy';
    anchor.append(img);
    const caption = document.createElement('figcaption');
    const number = document.createElement('span');
    number.textContent = `[${i + 1}]`;
    const description = document.createElement('span');
    description.textContent = item.caption[index];
    caption.append(number, description);
    figure.append(anchor, caption);
    evidenceCards.append(figure);
  });
  evidenceReferences.replaceChildren();
  (evidenceNotes[sceneId] || []).forEach((note, i) => {
    const anchor = document.createElement('a');
    anchor.href = note[3];
    anchor.target = '_blank';
    anchor.rel = 'noopener noreferrer';
    const number = document.createElement('span');
    number.textContent = `[${ids.length + i + 1}]`;
    const label = document.createElement('span');
    label.textContent = note[index];
    const arrow = document.createElement('small');
    arrow.textContent = t[6];
    anchor.append(number, label, arrow);
    evidenceReferences.append(anchor);
  });
}

function updateEvidenceScene() {
  if (evidenceDialog.open) return;
  let best = null;
  let bestDistance = Infinity;
  for (const scene of document.querySelectorAll('[data-scene]')) {
    const bounds = scene.getBoundingClientRect();
    if (bounds.bottom < 100 || bounds.top > innerHeight - 100) continue;
    const distance = Math.abs((bounds.top + bounds.bottom) / 2 - innerHeight / 2);
    if (distance < bestDistance) { best = scene.id; bestDistance = distance; }
  }
  if (best && (best !== evidenceCurrent || evidenceOpen.hidden)) {
    evidenceCurrent = best;
    renderEvidence(best);
  } else if (!best) evidenceOpen.hidden = true;
}

evidenceOpen.addEventListener('click', () => {
  evidenceLastFocus = document.activeElement;
  renderEvidence(evidenceCurrent);
  evidenceDialog.showModal();
  evidenceClose.focus();
});
evidenceClose.addEventListener('click', () => evidenceDialog.close());
evidenceDialog.addEventListener('click', event => {
  if (event.target === evidenceDialog) evidenceDialog.close();
});
evidenceDialog.addEventListener('close', () => {
  evidenceLastFocus?.focus();
  updateEvidenceScene();
});
document.getElementById('language').addEventListener('change', () => {
  requestAnimationFrame(() => renderEvidence(evidenceCurrent));
});
addEventListener('scroll', updateEvidenceScene, {passive: true});
addEventListener('resize', updateEvidenceScene);
updateEvidenceScene();
